const cell = t => t.replace(/\|/g, "\\|");
const tick = "`";

export const HANDBOOK_MD = SECTIONS.map(([title, head, rows]) => [
  `## ${title}`, "",
  `| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`,
  ...rows.map(([a, b, c]) => `| ${tick}${cell(a)}${tick} | ${tick}${cell(b)}${tick} | ${cell(c)} |`), "",
].join("\n")).join("\n");

export const HANDBOOK = [{ id: "built-in", title: "Command reference", md: HANDBOOK_MD }];
